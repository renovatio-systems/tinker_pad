#!/usr/bin/env python3
"""Makes the shop art: src/reck_shop.c and src/reck_shop.h.

Inputs (assets/reckalambo/sheet2/*.png, cut from the sprite sheet, plus the hammer source):
- three cars, scaled to one common size on a 160 x 96 canvas, bottom-aligned
- the bear, on a 64 x 96 canvas, bottom-aligned
- two hammer previews, 48 x 64: classic (green and red) and shiny black with gold
- four gems, 16 x 16
- three backgrounds, 480 x 320 (cropped from the middle of the wide pictures)

Sprites use RECK_KEY (0xF81F) for transparent pixels. Backgrounds are full RGB565.

Usage (from the repository root):
    python3 tools/make_shop_assets.py
"""

from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SHEET = ROOT / "assets" / "reckalambo" / "sheet2"
HAMMER_SRC = ROOT / "assets" / "reckalambo" / "hammer_sheet.png"
OUT_C = ROOT / "src" / "reck_shop.c"
OUT_H = ROOT / "src" / "reck_shop.h"
KEY = 0xF81F
CAR_W, CAR_H = 160, 96


def fit_sprite(path, w, h, scale=None, bottom=True):
    """Scale an RGBA sprite and place it on a w x h canvas. Returns RGB and alpha arrays."""
    im = Image.open(path)
    if im.mode != "RGBA":
        # No alpha channel: the magenta background is the transparent key.
        rgb = np.array(im.convert("RGB"))
        r, g, b = rgb[..., 0].astype(int), rgb[..., 1].astype(int), rgb[..., 2].astype(int)
        alpha = np.where((r > 200) & (g < 80) & (b > 200), 0, 255).astype(np.uint8)
        im = Image.fromarray(np.dstack([rgb, alpha]), "RGBA")
    else:
        im = im.convert("RGBA")
    if scale is None:
        scale = min(w / im.width, h / im.height)
    nw, nh = max(1, round(im.width * scale)), max(1, round(im.height * scale))
    small = im.resize((nw, nh), Image.Resampling.BOX)
    arr = np.array(small)
    rgb, a = arr[..., :3], arr[..., 3]
    canvas_rgb = np.zeros((h, w, 3), np.uint8)
    canvas_a = np.zeros((h, w), np.uint8)
    ox = (w - nw) // 2
    oy = h - nh if bottom else (h - nh) // 2
    canvas_rgb[oy:oy + nh, ox:ox + nw] = rgb
    canvas_a[oy:oy + nh, ox:ox + nw] = a
    return canvas_rgb, canvas_a, scale


def to_565_keyed(rgb, a):
    px = ((rgb[..., 0].astype(np.uint32) & 0xF8) << 8) | ((rgb[..., 1].astype(np.uint32) & 0xFC) << 3) | (rgb[..., 2].astype(np.uint32) >> 3)
    return np.where(a >= 128, px, KEY).astype(np.uint16).flatten()


def bg_565(path):
    im = Image.open(path).convert("RGB")
    h = 320
    w = round(im.width * h / im.height)
    im = im.resize((w, h), Image.Resampling.BOX)
    x0 = (w - 480) // 2
    im = im.crop((x0, 0, x0 + 480, 320))
    arr = np.array(im)
    px = ((arr[..., 0].astype(np.uint32) & 0xF8) << 8) | ((arr[..., 1].astype(np.uint32) & 0xFC) << 3) | (arr[..., 2].astype(np.uint32) >> 3)
    return px.astype(np.uint16).flatten()


def main():
    # One common scale for the three cars, so the wreck and the sports cars look the same size.
    names = ["car_pickup_red", "car_sports_silver", "car_sports_red"]
    widths = [Image.open(SHEET / f"{n}.png").width for n in names]
    car_scale = CAR_W / max(widths)
    cars = []
    for n in names:
        rgb, a, _ = fit_sprite(SHEET / f"{n}.png", CAR_W, CAR_H, scale=car_scale)
        cars.append(to_565_keyed(rgb, a))

    bear = to_565_keyed(*fit_sprite(SHEET / "bear.png", 64, 96)[:2])
    hammers = [
        to_565_keyed(*fit_sprite(HAMMER_SRC, 48, 64)[:2]),
        to_565_keyed(*fit_sprite(SHEET / "hammer_black_gold.png", 48, 64)[:2]),
    ]
    gems = [to_565_keyed(*fit_sprite(SHEET / f"gem_{n}.png", 16, 16)[:2])
            for n in ["diamond", "sapphire", "ruby", "emerald"]]
    bgs = [bg_565(SHEET / f"bg_{n}.png") for n in ["race_track", "english_town", "english_village"]]

    OUT_H.write_text(
        "#ifndef RECK_SHOP_H\n#define RECK_SHOP_H\n\n#include <stdint.h>\n\n"
        "// Generated by tools/make_shop_assets.py: do not edit.\n"
        "#define SHOP_CAR_W 160\n#define SHOP_CAR_H 96\n"
        "#define SHOP_BEAR_W 64\n#define SHOP_BEAR_H 96\n"
        "#define SHOP_HAMMER_W 48\n#define SHOP_HAMMER_H 64\n"
        "#define SHOP_GEM 16\n"
        "#define SHOP_BG_W 480\n#define SHOP_BG_H 320\n\n"
        "extern const uint16_t shop_car[3][SHOP_CAR_W * SHOP_CAR_H];     // pickup, silver sports car, red sports car\n"
        "extern const uint16_t shop_bear[SHOP_BEAR_W * SHOP_BEAR_H];\n"
        "extern const uint16_t shop_hammer[2][SHOP_HAMMER_W * SHOP_HAMMER_H]; // classic, shiny black\n"
        "extern const uint16_t shop_gem[4][SHOP_GEM * SHOP_GEM];           // diamond, sapphire, ruby, emerald\n"
        "extern const uint16_t shop_bg[3][SHOP_BG_W * SHOP_BG_H];          // race track, town, village\n\n"
        "#endif\n")

    def write_array(f, name, dims, data_list):
        f.write(f"const uint16_t {name}{dims} = {{\n")
        for arr in data_list:
            f.write("{\n")
            for i in range(0, len(arr), 12):
                f.write("    " + ", ".join(f"0x{v:04X}" for v in arr[i:i + 12]) + ",\n")
            f.write("},\n")
        f.write("};\n\n")

    with open(OUT_C, "w") as f:
        f.write("// Generated by tools/make_shop_assets.py: do not edit.\n#include \"reck_shop.h\"\n\n")
        write_array(f, "shop_car", "[3][SHOP_CAR_W * SHOP_CAR_H]", cars)
        f.write("const uint16_t shop_bear[SHOP_BEAR_W * SHOP_BEAR_H] = {\n")
        for i in range(0, len(bear), 12):
            f.write("    " + ", ".join(f"0x{v:04X}" for v in bear[i:i + 12]) + ",\n")
        f.write("};\n\n")
        write_array(f, "shop_hammer", "[2][SHOP_HAMMER_W * SHOP_HAMMER_H]", hammers)
        write_array(f, "shop_gem", "[4][SHOP_GEM * SHOP_GEM]", gems)
        write_array(f, "shop_bg", "[3][SHOP_BG_W * SHOP_BG_H]", bgs)
    print("car scale", round(car_scale, 4))


if __name__ == "__main__":
    main()
