#!/usr/bin/env python3
"""Cuts the jaguar out of assets/reckalambo/jaguar_sheet.png and writes src/reck_jaguar.c/.h.

The sheet has one sprite on flat magenta (#FF00FF). Its bounding box is scaled to fit a
64 x 96 canvas, bottom-aligned and centred, so the feet sit on the ground line. Magenta is
the transparent key (RECK_KEY, 0xF81F), and a pixel is kept only if most of its area was
sprite.

Usage (from the repository root):
    python3 tools/make_jaguar_sprite.py
"""

from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "reckalambo" / "jaguar_nohammer_sheet.png"
OUT_C = ROOT / "src" / "reck_jaguar.c"
OUT_H = ROOT / "src" / "reck_jaguar.h"
W, H = 64, 96
KEY = 0xF81F


def main():
    im = np.array(Image.open(SRC).convert("RGB"))
    r, g, b = im[..., 0].astype(int), im[..., 1].astype(int), im[..., 2].astype(int)
    mask = ~((r > 200) & (g < 80) & (b > 200))
    rows = np.where(mask.any(axis=1))[0]
    cols = np.where(mask.any(axis=0))[0]
    y0, y1, x0, x1 = rows.min(), rows.max() + 1, cols.min(), cols.max() + 1
    rgb = im[y0:y1, x0:x1].copy()
    m = mask[y0:y1, x0:x1].copy()
    rgb[~m] = 0

    scale = min(W / m.shape[1], H / m.shape[0])
    nw, nh = max(1, round(m.shape[1] * scale)), max(1, round(m.shape[0] * scale))
    col = np.array(Image.fromarray(rgb).resize((nw, nh), Image.Resampling.BOX))
    mm = np.array(Image.fromarray((m * 255).astype(np.uint8)).resize((nw, nh), Image.Resampling.BOX)) >= 128

    out_c = np.zeros((H, W, 3), np.uint8)
    out_m = np.zeros((H, W), bool)
    ox, oy = (W - nw) // 2, H - nh
    out_c[oy:oy + nh, ox:ox + nw] = col
    out_m[oy:oy + nh, ox:ox + nw] = mm

    rr, gg, bb = out_c[..., 0].astype(int), out_c[..., 1].astype(int), out_c[..., 2].astype(int)
    px = (((rr & 0xF8) << 8) | ((gg & 0xFC) << 3) | (bb >> 3))
    px = np.where(out_m, px, KEY).astype(np.uint16).flatten()

    OUT_H.write_text(
        "#ifndef RECK_JAGUAR_H\n#define RECK_JAGUAR_H\n\n#include <stdint.h>\n\n"
        "// Generated by tools/make_jaguar_sprite.py: do not edit.\n"
        "#define RECK_JAG_W 64\n#define RECK_JAG_H 96\n"
        "extern const uint16_t reck_jaguar[RECK_JAG_W * RECK_JAG_H];\n\n#endif\n"
    )
    lines = ["// Generated by tools/make_jaguar_sprite.py: do not edit.", '#include "reck_jaguar.h"', "",
             "const uint16_t reck_jaguar[RECK_JAG_W * RECK_JAG_H] = {"]
    for i in range(0, len(px), 12):
        lines.append("    " + ", ".join(f"0x{v:04X}" for v in px[i:i + 12]) + ",")
    lines += ["};", ""]
    OUT_C.write_text("\n".join(lines))
    print(f"sprite {m.shape[1]}x{m.shape[0]} scaled to {nw}x{nh}, scale {scale:.4f}")


if __name__ == "__main__":
    main()
