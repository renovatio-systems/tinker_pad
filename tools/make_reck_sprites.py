#!/usr/bin/env python3
"""Cuts the Reckalambo sprites out of assets/reckalambo/sprites_sheet.png.

The sheet has four sprites on flat magenta (#FF00FF), left to right: the intact Urus, the
wrecked Urus, a tumbling gorilla and a gorilla with its arms out. Each sprite is found by
its columns, cut to its bounding box, and scaled down:

- Both cars use the same scale, so the wreck keeps the size of the intact car. Each car is
  placed on a 160 x 96 canvas, bottom-aligned, with the smoke above the wreck.
- Each gorilla is fitted inside a 32 x 32 canvas, centred.

Magenta pixels are transparent. They are replaced with black before resizing, so no pink
fringe is left, and a pixel is kept only if most of its area was sprite.

Output: src/reck_sprites.h and src/reck_sprites.c, RGB565, key colour RECK_KEY (0xF81F).

Usage (from the repository root):
    python3 tools/make_reck_sprites.py
"""

from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "reckalambo" / "sprites_sheet.png"
OUT_C = ROOT / "src" / "reck_sprites.c"
OUT_H = ROOT / "src" / "reck_sprites.h"

CAR_W, CAR_H = 160, 96
GOR = 32
KEY = 0xF81F


def find_sprites(mask):
    cols = mask.any(axis=0)
    runs, start = [], None
    for x, v in enumerate(cols):
        if v and start is None:
            start = x
        if not v and start is not None:
            runs.append((start, x - 1))
            start = None
    if start is not None:
        runs.append((start, len(cols) - 1))
    boxes = []
    for a, b in runs:
        rows = np.where(mask[:, a:b + 1].any(axis=1))[0]
        boxes.append((a, rows.min(), b, rows.max()))
    return boxes


def cut(rgb, mask, box):
    x0, y0, x1, y1 = box
    return rgb[y0:y1 + 1, x0:x1 + 1].copy(), mask[y0:y1 + 1, x0:x1 + 1].copy()


def scaled(rgb, mask, scale):
    h, w = mask.shape
    nw, nh = max(1, round(w * scale)), max(1, round(h * scale))
    img = Image.fromarray(rgb)
    col = np.array(img.resize((nw, nh), Image.Resampling.BOX))
    m = np.array(Image.fromarray((mask * 255).astype(np.uint8)).resize((nw, nh), Image.Resampling.BOX))
    return col, m >= 128


def place(col, m, cw, ch, bottom=False):
    out_c = np.zeros((ch, cw, 3), np.uint8)
    out_m = np.zeros((ch, cw), bool)
    h, w = m.shape
    ox = (cw - w) // 2
    oy = (ch - h) if bottom else (ch - h) // 2
    out_c[oy:oy + h, ox:ox + w] = col
    out_m[oy:oy + h, ox:ox + w] = m
    return out_c, out_m


def to_565(rgb, mask):
    r, g, b = rgb[..., 0].astype(int), rgb[..., 1].astype(int), rgb[..., 2].astype(int)
    px = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
    return np.where(mask, px, KEY).astype(np.uint16)


def main():
    im = np.array(Image.open(SRC).convert("RGB"))
    r, g, b = im[..., 0].astype(int), im[..., 1].astype(int), im[..., 2].astype(int)
    key = (r > 200) & (g < 80) & (b > 200)
    mask = ~key
    boxes = find_sprites(mask)
    assert len(boxes) == 4, f"expected 4 sprites, found {len(boxes)}"

    parts = []
    for box in boxes:
        rgb, m = cut(im, mask, box)
        rgb = rgb.copy()
        rgb[~m] = 0
        parts.append((rgb, m))

    car_scale = CAR_W / max(p[1].shape[1] for p in parts[:2])
    car_intact = scaled(*parts[0], car_scale)
    car_wreck = scaled(*parts[1], car_scale)
    gor_scale_a = GOR / max(parts[2][1].shape)
    gor_scale_b = GOR / max(parts[3][1].shape)
    gor_a = scaled(*parts[2], gor_scale_a)
    gor_b = scaled(*parts[3], gor_scale_b)

    sprites = [
        ("reck_car_intact", *place(*car_intact, CAR_W, CAR_H, bottom=True), CAR_W, CAR_H),
        ("reck_car_wreck", *place(*car_wreck, CAR_W, CAR_H, bottom=True), CAR_W, CAR_H),
        ("reck_gorilla_tumble", *place(*gor_a, GOR, GOR), GOR, GOR),
        ("reck_gorilla_arms", *place(*gor_b, GOR, GOR), GOR, GOR),
    ]

    h_lines = [
        "#ifndef RECK_SPRITES_H",
        "#define RECK_SPRITES_H",
        "",
        "#include <stdint.h>",
        "",
        "// Generated by tools/make_reck_sprites.py: do not edit.",
        "// Transparent pixels are RECK_KEY. Car sprites are bottom-aligned on a 160 x 96 canvas.",
        f"#define RECK_KEY 0x{KEY:04X}",
        f"#define RECK_CAR_W {CAR_W}",
        f"#define RECK_CAR_H {CAR_H}",
        f"#define RECK_GOR_W {GOR}",
        f"#define RECK_GOR_H {GOR}",
        "",
    ]
    c_lines = ["// Generated by tools/make_reck_sprites.py: do not edit.", '#include "reck_sprites.h"', ""]
    for name, rgb, m, w, h in sprites:
        px = to_565(rgb, m)
        dim = "RECK_CAR" if "car" in name else "RECK_GOR"
        h_lines.append(f"extern const uint16_t {name}[{dim}_W * {dim}_H];")
        c_lines.append(f"const uint16_t {name}[{dim}_W * {dim}_H] = {{")
        flat = px.flatten()
        for i in range(0, len(flat), 12):
            c_lines.append("    " + ", ".join(f"0x{v:04X}" for v in flat[i:i + 12]) + ",")
        c_lines.append("};")
        c_lines.append("")
    h_lines += ["", "#endif"]
    OUT_H.write_text("\n".join(h_lines) + "\n")
    OUT_C.write_text("\n".join(c_lines) + "\n")
    print("car scale", round(car_scale, 4), "gorilla scales", round(gor_scale_a, 4), round(gor_scale_b, 4))


if __name__ == "__main__":
    main()
