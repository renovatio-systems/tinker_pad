#!/usr/bin/env python3
"""Makes the swinging hammer: twelve pre-rotated frames, one per tick of a swing.

Source: assets/reckalambo/hammer_sheet.png (one hammer on flat magenta, #FF00FF).
The hammer is scaled so the grip-to-head length is HEAD_LEN pixels, then placed on a
CANVAS x CANVAS canvas with the grip at the centre. Each frame is that image turned about the
grip, so the head moves through the swing.

The head angle phi (degrees, screen coordinates: y goes down) for swing tick f (1..12):
  f 1..6:  -120 .. -10  (raised behind, down to the car)
  f 6..12: -10  .. +10  (follow-through)
The head is at grip + HEAD_LEN * (cos phi, sin phi). The game uses the same offsets for
the hit test, so the hit and the picture agree.

Output: src/reck_hammer.h and src/reck_hammer.c. RECK_KEY (0xF81F) is transparent.

Usage (from the repository root):
    python3 tools/make_hammer_frames.py
"""

import math
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "reckalambo" / "hammer_sheet.png"
OUT_C = ROOT / "src" / "reck_hammer.c"
OUT_H = ROOT / "src" / "reck_hammer.h"

# In the source picture (1145 x 1374): grip pivot and the centre of the hammer head.
PIVOT_SRC = (240, 1080)
HEAD_SRC = (650, 370)
HEAD_LEN = 46          # pixels on the game screen
CANVAS = 128
KEY = 0xF81F
FRAMES = 12


def phi_for(f):
    if f <= 6:
        return -120 + (f - 1) * (110 / 5)
    return -10 + (f - 6) * (20 / 6)


def main():
    im = np.array(Image.open(SRC).convert("RGB"))
    r, g, b = im[..., 0].astype(int), im[..., 1].astype(int), im[..., 2].astype(int)
    key = (r > 200) & (g < 80) & (b > 200)
    mask = ~key
    ys, xs = np.where(mask)
    x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
    rgb = im[y0:y1, x0:x1].copy()
    m = mask[y0:y1, x0:x1].copy()
    rgb[~m] = 0

    src_len = math.hypot(HEAD_SRC[0] - PIVOT_SRC[0], HEAD_SRC[1] - PIVOT_SRC[1])
    s = HEAD_LEN / src_len
    nw, nh = max(1, round(m.shape[1] * s)), max(1, round(m.shape[0] * s))
    col = Image.fromarray(rgb).resize((nw, nh), Image.Resampling.BOX)
    mm = Image.fromarray((m * 255).astype(np.uint8)).resize((nw, nh), Image.Resampling.BOX)
    mm = np.array(mm) >= 128

    # Paste into a magenta canvas, with the pivot at its centre.
    px_s = (PIVOT_SRC[0] - x0) * s
    py_s = (PIVOT_SRC[1] - y0) * s
    base = Image.new("RGB", (CANVAS, CANVAS), (255, 0, 255))
    basem = np.zeros((CANVAS, CANVAS), bool)
    ox = int(round(CANVAS / 2 - px_s))
    oy = int(round(CANVAS / 2 - py_s))
    base_arr = np.array(base)
    col_arr = np.array(col)
    for yy in range(nh):
        for xx in range(nw):
            cx, cy = ox + xx, oy + yy
            if 0 <= cx < CANVAS and 0 <= cy < CANVAS and mm[yy, xx]:
                base_arr[cy, cx] = col_arr[yy, xx]
                basem[cy, cx] = True
    base = Image.fromarray(base_arr)

    # The hammer as drawn points at angle theta0 (visual, counter-clockwise, y up).
    vx, vy = HEAD_SRC[0] - PIVOT_SRC[0], -(HEAD_SRC[1] - PIVOT_SRC[1])
    theta0 = math.degrees(math.atan2(vy, vx))

    frames, offsets = [], []
    for f in range(1, FRAMES + 1):
        phi = phi_for(f)
        theta = -phi                       # screen angle to visual angle
        delta = theta - theta0            # PIL rotates counter-clockwise
        rot = np.array(base.rotate(delta, resample=Image.Resampling.NEAREST,
                                   center=(CANVAS / 2, CANVAS / 2), fillcolor=(255, 0, 255)))
        rr, gg, bb = rot[..., 0].astype(int), rot[..., 1].astype(int), rot[..., 2].astype(int)
        px = ((rr & 0xF8) << 8) | ((gg & 0xFC) << 3) | (bb >> 3)
        key_px = (rr > 200) & (gg < 80) & (bb > 200)
        frames.append(np.where(key_px, KEY, px).astype(np.uint16).flatten())
        offsets.append((round(HEAD_LEN * math.cos(math.radians(phi))),
                        round(HEAD_LEN * math.sin(math.radians(phi)))))

    OUT_H.write_text(
        "#ifndef RECK_HAMMER_H\n#define RECK_HAMMER_H\n\n#include <stdint.h>\n\n"
        "// Generated by tools/make_hammer_frames.py: do not edit.\n"
        f"#define RECK_HAMMER_FRAMES {FRAMES}\n"
        f"#define RECK_HAMMER_W {CANVAS}\n#define RECK_HAMMER_H_PX {CANVAS}\n"
        f"#define RECK_HAMMER_PIVOT {CANVAS // 2}  // the grip is at the centre of each frame\n"
        "// Head offset from the grip, for swing tick 1..12 (x, y).\n"
        "extern const int8_t reck_hammer_head[RECK_HAMMER_FRAMES][2];\n"
        "extern const uint16_t reck_hammer[RECK_HAMMER_FRAMES][RECK_HAMMER_W * RECK_HAMMER_H_PX];\n\n"
        "#endif\n"
    )
    lines = ["// Generated by tools/make_hammer_frames.py: do not edit.", '#include "reck_hammer.h"', "",
             "const int8_t reck_hammer_head[RECK_HAMMER_FRAMES][2] = {"]
    lines += [f"    {{{dx}, {dy}}}," for dx, dy in offsets]
    lines += ["};", "", "const uint16_t reck_hammer[RECK_HAMMER_FRAMES][RECK_HAMMER_W * RECK_HAMMER_H_PX] = {"]
    for fr in frames:
        lines.append("{")
        for i in range(0, len(fr), 12):
            lines.append("    " + ", ".join(f"0x{v:04X}" for v in fr[i:i + 12]) + ",")
        lines.append("},")
    lines += ["};", ""]
    OUT_C.write_text("\n".join(lines))
    print("scale", round(s, 4), "head offsets", offsets)


if __name__ == "__main__":
    main()
