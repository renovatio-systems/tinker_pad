#!/usr/bin/env python3
"""Turns the level 2 sprite images in assets/l2/ into C arrays in src/l2_sprites.c.

Each image is 1024 x 1024 with a solid magenta (#FF00FF) background. The script:
  1. marks magenta pixels as transparent (the game's colour key, SPRITE_KEY),
  2. crops to the fighter, scales it to fit the target size, keeping its proportions,
  3. stands it on the bottom edge of the target canvas, so the feet sit on the floor,
  4. writes RGB565 pixels, transparent pixels as SPRITE_KEY.

Each sprite is scaled to the height in SPRITES; the width follows its proportions.

Usage (from the repository root):
    python3 tools/make_l2_sprites.py
"""

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "l2"
OUT_C = ROOT / "src" / "l2_sprites.c"
OUT_H = ROOT / "src" / "l2_sprites.h"

SPRITE_KEY = 0xF81F  # RGB565 magenta, the same key as assets.h

# (file, C name, height in px). Jatayu is 134 px tall. The first Rakshasa is 100% of him, the
# second 105% and the third 110%. Each sprite keeps its own proportions, so its width comes from its height.
SPRITES = [
    ("jatayu.png", "l2_jatayu", 134),
    ("shadow_spearman.png", "l2_shadow_spearman", 134),
    ("blood_warrior.png", "l2_blood_warrior", 141),
    ("demon_commander.png", "l2_demon_commander", 147),
    # Jatayu for Level 3: 30% smaller than in Level 2.
    ("jatayu.png", "l3_jatayu", 94),
]


def is_magenta(r, g, b):
    return r > 200 and g < 80 and b > 200


def mask_and_crop(img):
    """Returns (rgb, opaque) where opaque is 0..255 per pixel, cropped to the fighter."""
    px = img.load()
    w, h = img.size
    opaque = Image.new("L", (w, h), 0)
    op = opaque.load()
    x0, y0, x1, y1 = w, h, -1, -1
    for y in range(h):
        for x in range(w):
            r, g, b = px[x, y]
            if not is_magenta(r, g, b):
                op[x, y] = 255
                x0, y0 = min(x0, x), min(y0, y)
                x1, y1 = max(x1, x), max(y1, y)
    if x1 < 0:
        raise SystemExit("no fighter found: the background is not magenta")
    box = (x0, y0, x1 + 1, y1 + 1)
    return img.crop(box), opaque.crop(box)


def fit(rgb, opaque, ch):
    """Scales the fighter to the height ch, feet on the bottom edge. Returns the canvas (cw x ch)."""
    bw, bh = rgb.size
    nh = ch
    nw = max(1, round(bw * ch / bh))
    cw = nw
    # BOX averages, so the coverage of each output pixel gives a clean edge.
    rgb = rgb.resize((nw, nh), Image.BOX)
    opaque = opaque.resize((nw, nh), Image.BOX)

    canvas_rgb = Image.new("RGB", (cw, ch), (255, 0, 255))
    canvas_a = Image.new("L", (cw, ch), 0)
    ox, oy = 0, 0
    canvas_rgb.paste(rgb, (ox, oy))
    canvas_a.paste(opaque, (ox, oy))
    return canvas_rgb, canvas_a


def to_rgb565(canvas_rgb, canvas_a):
    out = []
    rp, ap = canvas_rgb.load(), canvas_a.load()
    w, h = canvas_rgb.size
    for y in range(h):
        for x in range(w):
            if ap[x, y] < 128:
                out.append(SPRITE_KEY)
                continue
            r, g, b = rp[x, y]
            out.append(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3))
    return out


def c_array(name, pixels, w, h):
    lines = []
    for i in range(0, len(pixels), 16):
        lines.append("    " + ", ".join(f"0x{p:04X}" for p in pixels[i:i + 16]) + ",")
    return f"const uint16_t {name}[{name.upper()}_W * {name.upper()}_H] = {{\n" + "\n".join(lines) + "\n};\n"


def main():
    header = [
        "#ifndef L2_SPRITES_H",
        "#define L2_SPRITES_H",
        "",
        "#include <stdint.h>",
        "",
        "// Generated by tools/make_l2_sprites.py: do not edit.",
        "// Colour-keyed RGB565 sprites for level 2, with the feet on the bottom edge.",
        "",
    ]
    source = [
        "// Generated by tools/make_l2_sprites.py: do not edit.",
        '#include "l2_sprites.h"',
        "",
    ]
    for file, name, ch in SPRITES:
        img = Image.open(SRC / file).convert("RGB")
        rgb, opaque = mask_and_crop(img)
        canvas_rgb, canvas_a = fit(rgb, opaque, ch)
        cw = canvas_rgb.size[0]
        pixels = to_rgb565(canvas_rgb, canvas_a)
        upper = name.upper()
        header += [
            f"#define {upper}_W {cw}",
            f"#define {upper}_H {ch}",
            f"extern const uint16_t {name}[{upper}_W * {upper}_H];",
            "",
        ]
        source.append(c_array(name, pixels, cw, ch))
        print(f"{file}: {cw} x {ch}")
    header += ["#endif", ""]
    OUT_H.write_text("\n".join(header))
    OUT_C.write_text("\n".join(source))


if __name__ == "__main__":
    main()
