#!/usr/bin/env python3
"""Converts the Level 3 artwork in assets/level3/ into C arrays in src/l3_assets.c.

Sprites have a solid magenta (#FF00FF) background. For them the script:
  1. crops to the visible part (everything that isn't magenta),
  2. scales it to fit the game size, keeping its proportions (nearest neighbour, so the pixels
     stay crisp),
  3. writes RGB565, with magenta as SPRITE_KEY, the same key the other levels use.

Full-screen pictures (the story image, the temple strip, the cloud tile) have no key. They are
cropped to the target's proportions and scaled to the exact size.

Usage (from the repository root):
    python3 tools/make_l3_assets.py [preview_dir]
A preview PNG of each converted asset is written to preview_dir, if given.
"""

import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "level3"
OUT_C = ROOT / "src" / "l3_assets.c"
OUT_H = ROOT / "src" / "l3_assets.h"

SPRITE_KEY = 0xF81F  # RGB565 magenta, the same key as the other levels

# (file, C name, game width, game height, mode). Modes:
#   key   - a sprite on magenta: crop to the visible part, fit, keep magenta as transparent
#   full  - a picture with no key, scaled to the exact size
#   cloud - the cloud tile: a centred crop to the target's 2:1 proportions, then scaled
ASSETS = [
    ("story_ravana_kidnaps_sita.png", "l3_story", 480, 320, "full"),
    ("pushpaka_vimana.png", "l3_pushpaka_vimana", 160, 96, "key"),
    ("temple_platform.png", "l3_temple_platform", 48, 12, "key"),
    ("cloud_platform.png", "l3_cloud_platform", 48, 14, "key"),
    ("lotus_platform.png", "l3_lotus_platform", 40, 12, "key"),
    ("dark_stone_platform.png", "l3_dark_stone_platform", 48, 12, "key"),
    ("diya_lamp.png", "l3_diya_lamp", 12, 16, "key"),
    ("temple_silhouette_strip.png", "l3_temple_strip", 480, 96, "full"),
    ("cloud_tile.png", "l3_cloud_tile", 64, 32, "cloud"),
    ("blood_moon.png", "l3_blood_moon", 120, 120, "key"),
]


def is_key(r, g, b):
    # Magenta, and the purple-pink edge pixels that blend into it. Pink petals and gold trim have
    # more green than that, so they are kept.
    return r >= 120 and b >= 120 and g + 70 <= min(r, b)


def visible_box(img):
    """The bounding box of everything that isn't magenta."""
    px = img.load()
    w, h = img.size
    x0, y0, x1, y1 = w, h, -1, -1
    for y in range(h):
        for x in range(w):
            if not is_key(*px[x, y][:3]):
                x0, y0, x1, y1 = min(x0, x), min(y0, y), max(x1, x), max(y1, y)
    if x1 < 0:
        raise SystemExit("no visible pixels: is the magenta background missing?")
    return (x0, y0, x1 + 1, y1 + 1)


def fit_keyed(img, tw, th):
    """Crop to the visible part, scale to fit tw x th keeping proportions, centre on a magenta canvas."""
    img = img.crop(visible_box(img))
    bw, bh = img.size
    scale = min(tw / bw, th / bh)
    nw, nh = max(1, round(bw * scale)), max(1, round(bh * scale))
    small = img.resize((nw, nh), Image.NEAREST)
    canvas = Image.new("RGB", (tw, th), (255, 0, 255))
    canvas.paste(small, ((tw - nw) // 2, (th - nh) // 2))
    return canvas


def fit_full(img, tw, th):
    return img.resize((tw, th), Image.NEAREST)


def fit_cloud(img, tw, th):
    """A centred crop to the target's proportions, so the cloud isn't squashed."""
    w, h = img.size
    want_h = w * th // tw
    top = (h - want_h) // 2
    return img.crop((0, top, w, top + want_h)).resize((tw, th), Image.NEAREST)


def to_rgb565(canvas, keyed):
    px = canvas.load()
    w, h = canvas.size
    out = []
    for y in range(h):
        for x in range(w):
            r, g, b = px[x, y]
            if keyed and is_key(r, g, b):
                out.append(SPRITE_KEY)
            else:
                out.append(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3))
    return out


def rgb_from_565(v):
    r = ((v >> 11) & 0x1F) * 255 // 31
    g = ((v >> 5) & 0x3F) * 255 // 63
    b = (v & 0x1F) * 255 // 31
    return (r, g, b)


def c_array(name, pixels):
    lines = []
    for i in range(0, len(pixels), 16):
        lines.append("    " + ", ".join(f"0x{p:04X}" for p in pixels[i:i + 16]) + ",")
    return f"const uint16_t {name}[{name.upper()}_W * {name.upper()}_H] = {{\n" + "\n".join(lines) + "\n};\n"


def main():
    preview_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else None
    header = [
        "#ifndef L3_ASSETS_H",
        "#define L3_ASSETS_H",
        "",
        "#include <stdint.h>",
        "",
        "// Generated by tools/make_l3_assets.py: do not edit.",
        "// Level 3 artwork, RGB565, in flash. SPRITE_KEY (0xF81F) marks transparent pixels.",
        "",
    ]
    source = ["// Generated by tools/make_l3_assets.py: do not edit.", '#include "l3_assets.h"', ""]
    for file, name, tw, th, mode in ASSETS:
        img = Image.open(SRC / file).convert("RGB")
        if mode == "key":
            canvas = fit_keyed(img, tw, th)
        elif mode == "cloud":
            canvas = fit_cloud(img, tw, th)
        else:
            canvas = fit_full(img, tw, th)
        keyed = mode == "key"
        pixels = to_rgb565(canvas, keyed)
        upper = name.upper()
        header += [
            f"#define {upper}_W {tw}",
            f"#define {upper}_H {th}",
            f"extern const uint16_t {name}[{upper}_W * {upper}_H];",
            "",
        ]
        source.append(c_array(name, pixels))
        print(f"{file}: {tw} x {th} ({mode})")
        if preview_dir:
            preview_dir.mkdir(parents=True, exist_ok=True)
            out = Image.new("RGB", (tw, th))
            op = out.load()
            for i, v in enumerate(pixels):
                op[i % tw, i // tw] = (40, 40, 40) if keyed and v == SPRITE_KEY else rgb_from_565(v)
            out.resize((tw * 4, th * 4), Image.NEAREST).save(preview_dir / f"{name}.png")
    header += ["#endif", ""]
    OUT_H.write_text("\n".join(header))
    OUT_C.write_text("\n".join(source))


if __name__ == "__main__":
    main()
