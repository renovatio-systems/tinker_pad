#!/usr/bin/env python3
"""Renders the Sanskrit labels (स्तर and भाग) into src/l_labels.c.

The game's built-in font is ASCII only, so the Devanagari text is drawn here with Noto Sans
Devanagari and stored as a one-colour mask. Each label is drawn in the game in any colour: the
opaque pixels are painted with the colour asked for, and the rest is transparent (SPRITE_KEY).

Usage (from the repository root):
    python3 tools/make_labels.py
"""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
OUT_C = ROOT / "src" / "l_labels.c"
OUT_H = ROOT / "src" / "l_labels.h"
FONT = "/usr/share/fonts/truetype/noto/NotoSansDevanagari-Bold.ttf"
SPRITE_KEY = 0xF81F

# (C name, text, font size in pixels). Big labels are for titles, small ones for the top bar.
LABELS = [
    ("l_level_1_big", "स्तर १", 36),
    ("l_level_2_big", "स्तर २", 36),
    ("l_level_3_big", "स्तर ३", 36),
    ("l_level_4_big", "स्तर ४", 36),
    ("l_part_1_big", "भाग १", 36),
    ("l_part_2_big", "भाग २", 36),
    ("l_part_3_big", "भाग ३", 36),
    ("l_part_1_small", "भाग १", 18),
    ("l_part_2_small", "भाग २", 18),
    ("l_part_3_small", "भाग ३", 18),
]


def render(text, size):
    font = ImageFont.truetype(FONT, size)
    pad = 4
    probe = Image.new("L", (1, 1))
    x0, y0, x1, y1 = ImageDraw.Draw(probe).textbbox((0, 0), text, font=font, direction="ltr", features=None)
    w, h = x1 - x0 + 2 * pad, y1 - y0 + 2 * pad
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((pad - x0, pad - y0), text, font=font, fill=255)
    # Hard edges: a pixel is on if it is at least half covered.
    return img.point(lambda v: 255 if v >= 128 else 0)


def main():
    header = [
        "#ifndef L_LABELS_H",
        "#define L_LABELS_H",
        "",
        "#include <stdint.h>",
        "",
        "// Generated by tools/make_labels.py: do not edit.",
        "// One-colour masks: 0xFFFF where the label is drawn, SPRITE_KEY elsewhere.",
        "",
    ]
    source = ["// Generated by tools/make_labels.py: do not edit.", '#include "l_labels.h"', ""]
    for name, text, size in LABELS:
        mask = render(text, size)
        w, h = mask.size
        pixels = [0xFFFF if mask.getpixel((x, y)) else SPRITE_KEY for y in range(h) for x in range(w)]
        upper = name.upper()
        header += [
            f"#define {upper}_W {w}",
            f"#define {upper}_H {h}",
            f"extern const uint16_t {name}[{upper}_W * {upper}_H];",
            "",
        ]
        lines = ["    " + ", ".join(f"0x{p:04X}" for p in pixels[i:i + 16]) + "," for i in range(0, len(pixels), 16)]
        source.append(f"const uint16_t {name}[{upper}_W * {upper}_H] = {{\n" + "\n".join(lines) + "\n};\n")
        print(f"{name}: {w} x {h}  {text}")
    header += ["#endif", ""]
    OUT_H.write_text("\n".join(header))
    OUT_C.write_text("\n".join(source))


if __name__ == "__main__":
    main()
