#!/usr/bin/env python3
"""Turns assets/reckalambo/title_screen.png into src/title_img.c and src/title_img.h.

The source has black bars above and below the artwork. They are cropped, the art is scaled
to 480 pixels wide with box averaging, and it is centred on a 480 x 320 black canvas. The
black bands at the top and bottom leave room for the game's text.

Usage (from the repository root):
    python3 tools/make_title_img.py
"""

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "reckalambo" / "title_screen.png"
OUT_C = ROOT / "src" / "title_img.c"
OUT_H = ROOT / "src" / "title_img.h"
W, H = 480, 320
BAR_THRESHOLD = 24  # a row whose brightest pixel is below this counts as black bar


def main():
    im = Image.open(SRC).convert("RGB")
    px = im.load()
    w, h = im.size

    def row_is_bar(y):
        return all(max(px[x, y]) < BAR_THRESHOLD for x in range(0, w, 4))

    top = 0
    while top < h and row_is_bar(top):
        top += 1
    bottom = h - 1
    while bottom > top and row_is_bar(bottom):
        bottom -= 1
    art = im.crop((0, top, w, bottom + 1))

    art_h = round(art.height * W / art.width)
    art = art.resize((W, art_h), Image.Resampling.BOX)

    canvas = Image.new("RGB", (W, H), (0, 0, 0))
    y0 = (H - art_h) // 2
    canvas.paste(art, (0, y0))

    pixels = []
    cpx = canvas.load()
    for y in range(H):
        for x in range(W):
            r, g, b = cpx[x, y]
            pixels.append(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3))

    OUT_H.write_text(
        "#ifndef TITLE_IMG_H\n"
        "#define TITLE_IMG_H\n\n"
        "#include <stdint.h>\n\n"
        "// Generated by tools/make_title_img.py: do not edit.\n"
        "#define TITLE_IMG_W 480\n"
        "#define TITLE_IMG_H_PX 320\n"
        "extern const uint16_t title_img[TITLE_IMG_W * TITLE_IMG_H_PX];\n\n"
        "#endif\n"
    )
    lines = ["// Generated by tools/make_title_img.py: do not edit.", '#include "title_img.h"', "",
             "const uint16_t title_img[TITLE_IMG_W * TITLE_IMG_H_PX] = {"]
    for i in range(0, len(pixels), 12):
        lines.append("    " + ", ".join(f"0x{p:04X}" for p in pixels[i:i + 12]) + ",")
    lines.append("};")
    OUT_C.write_text("\n".join(lines) + "\n")
    print(f"art rows {top}-{bottom}, scaled to {W}x{art_h}, placed at y={y0}")


if __name__ == "__main__":
    main()
