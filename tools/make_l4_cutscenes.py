#!/usr/bin/env python3
"""Converts the Level 4 cut-scene pictures in assets/level4/cutscenes/ into src/l4_cutscenes.c.

Each picture is resized to 480 x 320 (if needed) and stored as RGB565 in flash. Scene 5 (cut_5_rama.png) is included
when it is present.

Usage (from the repository root):
    python3 tools/make_l4_cutscenes.py
"""

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "level4" / "cutscenes"
OUT_C = ROOT / "src" / "l4_cutscenes.c"
OUT_H = ROOT / "src" / "l4_cutscenes.h"
W, H = 480, 320
SCENES = [1, 2, 3, 4, 5]


def to_rgb565(img):
    px = img.load()
    out = []
    for y in range(H):
        for x in range(W):
            r, g, b = px[x, y]
            out.append(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3))
    return out


def main():
    header = [
        "#ifndef L4_CUTSCENES_H",
        "#define L4_CUTSCENES_H",
        "",
        "#include <stdint.h>",
        "",
        "// Generated by tools/make_l4_cutscenes.py: do not edit.",
        f"#define L4_CUT_W {W}",
        f"#define L4_CUT_H {H}",
        "",
    ]
    source = ["// Generated by tools/make_l4_cutscenes.py: do not edit.", '#include "l4_cutscenes.h"', ""]
    present = []
    for n in SCENES:
        path = SRC / f"cut_{n}_{['abduction', 'battle', 'wings', 'fall', 'rama'][n - 1]}.png"
        name = f"l4_cut_{n}"
        if not path.exists():
            print(f"{path.name}: not supplied, skipped")
            continue
        img = Image.open(path).convert("RGB")
        if img.size != (W, H):
            # Full-size originals (1536 x 1024) are resized to the screen; the 3:2 aspect is kept.
            img = img.resize((W, H), Image.LANCZOS)
        pixels = to_rgb565(img)
        header.append(f"extern const uint16_t {name}[L4_CUT_W * L4_CUT_H];")
        lines = ["    " + ", ".join(f"0x{p:04X}" for p in pixels[i:i + 16]) + "," for i in range(0, len(pixels), 16)]
        source.append(f"const uint16_t {name}[L4_CUT_W * L4_CUT_H] = {{\n" + "\n".join(lines) + "\n};\n")
        present.append(n)
        print(f"{path.name}: {W} x {H}")
    header += ["", "#endif", ""]
    OUT_H.write_text("\n".join(header))
    OUT_C.write_text("\n".join(source))
    print("scenes present:", present)


if __name__ == "__main__":
    main()
